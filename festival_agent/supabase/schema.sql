create or replace function dismiss_review(p_id bigint, p_code text)
returns jsonb
language plpgsql security definer set search_path = public, extensions as $$
declare
  v_err text;
  v_row classification%rowtype;
begin
  v_err := admin_gate(p_code);
  if v_err is not null then
    return jsonb_build_object('ok', false, 'error', v_err);
  end if;
  select * into v_row from classification where feedback_id = p_id for update;
  if not found then
    raise exception '없는 민원입니다';
  end if;
  if v_row.status <> 'review' then
    raise exception '이미 처리된 민원입니다';
  end if;
  update classification
     set status = 'dismissed', review_action = 'dismissed', decided_by = 'operator',
         reviewed_at = to_char(now() at time zone 'Asia/Seoul', 'YYYY-MM-DD"T"HH24:MI:SS')
   where feedback_id = p_id;
  return jsonb_build_object('ok', true);
end $$;

-- 되돌리기: 닫은 것(dismissed)이나 운영자가 지정한 것(done + decided_by='operator')을 다시 'review' 로.
create or replace function reopen_review(p_id bigint, p_code text)
returns jsonb
language plpgsql security definer set search_path = public, extensions as $$
declare
  v_err text;
  v_row classification%rowtype;
  v_raw text;
  v_was_label boolean;
begin
  v_err := admin_gate(p_code);
  if v_err is not null then
    return jsonb_build_object('ok', false, 'error', v_err);
  end if;
  select * into v_row from classification where feedback_id = p_id for update;
  if not found then
    raise exception '없는 민원입니다';
  end if;
  v_was_label := v_row.status = 'done' and v_row.decided_by = 'operator';
  if not (v_row.status = 'dismissed' or v_was_label) then
    raise exception '되돌릴 수 있는 처리가 아닙니다';
  end if;
  update classification
     set status = 'review', label = null, confidence = null,
         agent_note = '확인 필요 — 운영자가 되돌림. 모델 제안: ' || coalesce(v_row.suggested_label, '-'),
         reviewed_at = null, review_action = null, decided_by = null
   where feedback_id = p_id;
  if v_was_label then                                  -- 지정하며 넣어 둔 같은 문장 캐시는 지운다
    select raw_text into v_raw from feedback where id = p_id;
    delete from classify_cache where hash = encode(digest(v_raw, 'sha256'), 'hex');
  end if;
  return jsonb_build_object('ok', true);
end $$;

