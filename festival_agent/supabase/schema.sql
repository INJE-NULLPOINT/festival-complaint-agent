-- 민원 접수. 접수번호(inbox id)를 돌려준다.
create or replace function submit_feedback(p_zone_id bigint, p_text text)
returns bigint
language plpgsql security definer set search_path = public as $$
declare v_id bigint;
begin
  -- 한글·영문·숫자가 2개 이상이어야 한다 ('...' 'ㅋㅋ' '!!!!' 거부). core/privacy.has_content 와 같은 규칙
  if p_text is null or length(regexp_replace(p_text, '[^가-힣A-Za-z0-9]', '', 'g')) < 2 then
    raise exception '어떤 불편인지 조금 더 적어 주세요';
  end if;
  if length(p_text) > 500 then
    raise exception '500자 이내로 적어 주세요';
  end if;
  if not exists (select 1 from zone where id = p_zone_id) then
    raise exception '구역을 선택해 주세요';
  end if;
  insert into feedback_inbox (zone_id, text, created_at)
  values (p_zone_id, btrim(p_text), to_char(now() at time zone 'Asia/Seoul', 'YYYY-MM-DD"T"HH24:MI:SS'))
  returning id into v_id;
  return v_id;
end $$;

-- ── 관리자 RPC (운영자 코드 p_code 필요) ──────────────────────────────
-- 코드가 틀렸을 때 예외(raise)를 던지면 그 트랜잭션이 롤백돼 '틀린 시도' 기록도 사라진다.
-- 그래서 코드 검사 결과는 예외가 아니라 반환값으로 준다: {"ok": true, ...} / {"ok": false, "error": "…"}.
-- (없는 민원·잘못된 상태 같은 검증 오류는 코드를 통과한 뒤의 일이라 예외 그대로다.)
-- 예전 시그니처(코드 인자 없음)는 지운다 — 남겨 두면 anon 이 코드 없이 그대로 호출할 수 있다.
drop function if exists request_doc(text);
drop function if exists set_action_status(bigint, text);
drop function if exists delete_feedback(bigint);
drop function if exists restore_feedback(bigint);

-- 코드 검사 (내부용). 통과하면 null, 아니면 거부 사유를 돌려준다. anon 이 직접 부를 수 없다.
create or replace function admin_gate(p_code text)
returns text
language plpgsql security definer set search_path = public, extensions as $$
declare
  v_hash text;
  v_fails integer;
  v_ip text;
  v_src text := '';
begin
  select code_hash into v_hash from operator_secret where id = 1;
  if v_hash is null then
    return '운영자 코드가 필요합니다';            -- 코드를 안 정했으면 전부 거부
  end if;
  -- 출처별 실패 횟수 (D5-40). PostgREST 가 넘겨 주는 x-forwarded-for 의 첫 값을 '오늘 날짜 + 코드 해시'를 키로 해시한다.
  -- [확인 필요] Supabase 적용 시 이 헤더가 실제로 오는지 확인. 안 오면 v_src 는 '' — 예전처럼 전체가 한 출처로 묶인다.
  begin
    v_ip := trim(split_part(coalesce(current_setting('request.headers', true)::json->>'x-forwarded-for', ''), ',', 1));
  exception when others then
    v_ip := '';
  end;
  if v_ip <> '' then
    v_src := left(encode(hmac(v_ip, v_hash || to_char(current_date, 'YYYY-MM-DD'), 'sha256'), 'hex'), 16);
  end if;
  delete from admin_attempt                                                   -- 실패 기록은 24시간 뒤 삭제
   where at < to_char((now() - interval '24 hours') at time zone 'Asia/Seoul', 'YYYY-MM-DD"T"HH24:MI:SS');
  select count(*) into v_fails from admin_attempt
   where coalesce(src, '') = v_src
     and at >= to_char((now() - interval '10 minutes') at time zone 'Asia/Seoul', 'YYYY-MM-DD"T"HH24:MI:SS');
  if v_fails >= 5 then
    return '시도가 너무 많습니다. 10분 뒤에 다시 시도하세요';   -- 잠금 중에는 맞는 코드도 거부
  end if;
  if p_code is null or p_code = '' then
    return '운영자 코드가 필요합니다';            -- 코드를 안 보낸 요청은 실패로 세지 않는다
  end if;
  if crypt(p_code, v_hash) = v_hash then
    delete from admin_attempt where coalesce(src, '') = v_src;   -- 맞으면 이 출처의 실패 기록만 비운다
    return null;
  end if;
  insert into admin_attempt (at, src)
  values (to_char(now() at time zone 'Asia/Seoul', 'YYYY-MM-DD"T"HH24:MI:SS'), v_src);
  return '운영자 코드가 필요합니다';
end $$;

-- 코드가 맞는지만 확인 (코드 입력 창용)
create or replace function check_admin(p_code text)
returns jsonb
language plpgsql security definer set search_path = public, extensions as $$
declare v_err text;
begin
  v_err := admin_gate(p_code);
  if v_err is not null then
    return jsonb_build_object('ok', false, 'error', v_err);
  end if;
  return jsonb_build_object('ok', true);
end $$;

-- 조치요청서 생성 요청. 같은 유형이 이미 대기 중이면 그 요청 id 를 돌려준다.
create or replace function request_doc(p_label text, p_code text)
returns jsonb
language plpgsql security definer set search_path = public, extensions as $$
declare
  v_err text;
  v_id bigint;
begin
  v_err := admin_gate(p_code);
  if v_err is not null then
    return jsonb_build_object('ok', false, 'error', v_err);
  end if;
  if not exists (select 1 from department_map where label = p_label) then
    raise exception '모르는 민원 유형입니다: %', p_label;
  end if;
  select id into v_id from doc_job
   where label = p_label and status in ('queued', 'running') limit 1;
  if v_id is null then
    insert into doc_job (label, created_at)
    values (p_label, to_char(now() at time zone 'Asia/Seoul', 'YYYY-MM-DD"T"HH24:MI:SS'))
    returning id into v_id;
  end if;
  return jsonb_build_object('ok', true, 'id', v_id);
end $$;

-- 조치 상태 변경 (요청 → 조치중 → 완료)
create or replace function set_action_status(p_id bigint, p_status text, p_code text)
returns jsonb
language plpgsql security definer set search_path = public, extensions as $$
declare v_err text;
begin
  v_err := admin_gate(p_code);
  if v_err is not null then
    return jsonb_build_object('ok', false, 'error', v_err);
  end if;
  if p_status not in ('requested', 'in_progress', 'done') then
    raise exception '잘못된 상태: %', p_status;
  end if;
  update action_request
     set status = p_status,
         closed_at = case when p_status = 'done'
                          then to_char(now() at time zone 'Asia/Seoul', 'YYYY-MM-DD"T"HH24:MI:SS')
                          else null end
   where id = p_id;
  return jsonb_build_object('ok', true);
end $$;

-- 민원 숨김·되돌리기 (관제 '민원 지우기'). 행은 지우지 않고 deleted_at 만 바꾼다.
-- 건수·심각도·알림·브리핑·인용·카드는 deleted_at IS NULL 인 민원만 센다.
create or replace function delete_feedback(p_id bigint, p_code text)
returns jsonb
language plpgsql security definer set search_path = public, extensions as $$
declare v_err text;
begin
  v_err := admin_gate(p_code);
  if v_err is not null then
    return jsonb_build_object('ok', false, 'error', v_err);
  end if;
  update feedback
     set deleted_at = to_char(now() at time zone 'Asia/Seoul', 'YYYY-MM-DD"T"HH24:MI:SS')
   where id = p_id;
  if not found then
    raise exception '없는 민원입니다';
  end if;
  return jsonb_build_object('ok', true);
end $$;

create or replace function restore_feedback(p_id bigint, p_code text)
returns jsonb
language plpgsql security definer set search_path = public, extensions as $$
declare v_err text;
begin
  v_err := admin_gate(p_code);
  if v_err is not null then
    return jsonb_build_object('ok', false, 'error', v_err);
  end if;
  update feedback set deleted_at = null where id = p_id;
  if not found then
    raise exception '없는 민원입니다';
  end if;
  return jsonb_build_object('ok', true);
end $$;

-- ── 확인 필요(review) 처리 (D5-32) — 운영자 코드 필요, 상태 조건을 건다 ──────────
-- 유형 지정: status='review' → 'done'. 안전·혼잡이면 안전 의심 자동, 긍정은 안전 아님, 그 밖엔 p_is_safety(없으면 모델 값).
-- 같은 문장이 다시 오면 쓰도록 classify_cache 에도 넣는다 (Python 의 sha256(raw_text) 와 같은 해시).
create or replace function resolve_review(p_id bigint, p_label text, p_is_safety boolean, p_code text)
returns jsonb
language plpgsql security definer set search_path = public, extensions as $$
declare
  v_err text;
  v_row classification%rowtype;
  v_raw text;
  v_safe integer;
  v_now text := to_char(now() at time zone 'Asia/Seoul', 'YYYY-MM-DD"T"HH24:MI:SS');
begin
  v_err := admin_gate(p_code);
  if v_err is not null then
    return jsonb_build_object('ok', false, 'error', v_err);
  end if;
  if p_label not in ('parking', 'restroom', 'price', 'guide', 'crowd', 'safety', 'positive') then
    raise exception '모르는 민원 유형입니다: %', p_label;
  end if;
  select * into v_row from classification where feedback_id = p_id for update;   -- 두 운영자가 동시에 눌러도 한 번만
  if not found then
    raise exception '없는 민원입니다';
  end if;
  if v_row.status <> 'review' then
    raise exception '이미 처리된 민원입니다';
  end if;
  v_safe := case when p_label in ('safety', 'crowd') then 1
                 when p_label = 'positive' then 0
                 when p_is_safety is null then coalesce(v_row.is_safety, 0)
                 when p_is_safety then 1 else 0 end;
  update classification
     set label = p_label, is_safety = v_safe, confidence = 1.0, status = 'done',
         agent_note = '운영자 지정 (모델 제안: ' || coalesce(v_row.suggested_label, '-') || ')',
         reviewed_at = v_now, review_action = 'label', decided_by = 'operator'
   where feedback_id = p_id;
  select raw_text into v_raw from feedback where id = p_id;
  insert into classify_cache (hash, result)
  values (encode(digest(v_raw, 'sha256'), 'hex'),
          json_build_object('label', p_label, 'sentiment', coalesce(v_row.sentiment, -0.5),
                            'is_safety', v_safe = 1, 'confidence', 1.0)::text)
  on conflict (hash) do update set result = excluded.result;
  return jsonb_build_object('ok', true);
end $$;

