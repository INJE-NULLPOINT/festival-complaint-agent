-- 요청한 쪽의 '출처' 해시 (내부용, D5-40·D5-33). PostgREST 가 넘겨 주는 x-forwarded-for 의 **맨 오른쪽** 값을
-- '오늘 날짜 + 코드 해시'를 키로 HMAC 해서 앞 16자만 쓴다. 원문 IP 는 저장하지 않는다. 헤더가 없으면 '' (출처를 모름).
-- 맨 오른쪽만 쓰는 이유(D5-43): 게이트웨이가 마지막에 덧붙인 값이고, 왼쪽은 접속한 쪽이 직접 넣어 보낸 것일 수 있다.
-- [확인 필요] Supabase 적용 시 ①이 헤더가 실제로 오는지 ②맨 오른쪽이 게이트웨이가 붙인 접속자 주소인지(앞에 프록시가 더 있으면
-- 오른쪽에서 n번째) 확인. 안 오면 '' — 운영자 코드 잠금은 전체 공용, 출처별 폭주 제한(②)은 건너뛴다.
create or replace function request_source()
returns text
language plpgsql stable security definer set search_path = public, extensions as $$
declare
  v_hdr text;
  v_parts text[];
  v_ip text;
  v_key text;
begin
  begin
    v_hdr := coalesce(current_setting('request.headers', true)::json->>'x-forwarded-for', '');
  exception when others then
    v_hdr := '';
  end;
  v_parts := string_to_array(v_hdr, ',');
  v_ip := trim(coalesce(v_parts[greatest(coalesce(array_length(v_parts, 1), 1), 1)], ''));
  if v_ip = '' then
    return '';
  end if;
  select code_hash into v_key from operator_secret where id = 1;
  if v_key is null then
    return '';                                   -- 비밀값이 없으면 출처를 구분하지 않는다 (고정 문자열 키는 쓰지 않는다)
  end if;
  return left(encode(hmac(v_ip, v_key || to_char(current_date, 'YYYY-MM-DD'), 'sha256'), 'hex'), 16);
end $$;

-- 코드 검사 (내부용). 통과하면 null, 아니면 거부 사유를 돌려준다. anon 이 직접 부를 수 없다.
create or replace function admin_gate(p_code text)
returns text
language plpgsql security definer set search_path = public, extensions as $$
declare
  v_hash text;
  v_fails integer;
  v_src text := '';
begin
  select code_hash into v_hash from operator_secret where id = 1;
  if v_hash is null then
    return '운영자 코드가 필요합니다';            -- 코드를 안 정했으면 전부 거부
  end if;
  v_src := request_source();            -- 출처별 실패 횟수 (D5-40) — 해시 규칙은 request_source() 참고
  delete from admin_attempt                                                   -- 실패 기록은 24시간 뒤 삭제
   where at < to_char((now() - interval '24 hours') at time zone 'Asia/Seoul', 'YYYY-MM-DD"T"HH24:MI:SS');
  select count(*) into v_fails from admin_attempt
   where coalesce(src, '') = v_src
     and at >= to_char((now() - interval '10 minutes') at time zone 'Asia/Seoul', 'YYYY-MM-DD"T"HH24:MI:SS');
  if v_fails >= 5 then
    return '시도가 너무 많습니다. 10분 뒤에 다시 시도하세요';   -- 잠금 중에는 맞는 코드도 거부
  end if;
  if p_code is null or p_code = '' then
    return '운영자 코드가 필요합니다';            -- 코드를 안 보낸 요청은 실패로 세지 않는다
  end if;
  if crypt(p_code, v_hash) = v_hash then
    delete from admin_attempt where coalesce(src, '') = v_src;   -- 맞으면 이 출처의 실패 기록만 비운다
    return null;
  end if;
  insert into admin_attempt (at, src)
  values (to_char(now() at time zone 'Asia/Seoul', 'YYYY-MM-DD"T"HH24:MI:SS'), v_src);
  return '운영자 코드가 필요합니다';
end $$;

