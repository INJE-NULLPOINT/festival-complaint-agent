-- ── 운영자 코드 (할일 D5-31) ──────────────────────────────────────────
-- 민원 지우기·되돌리기, 조치 상태 변경, 조치요청서 생성은 운영자 코드가 맞을 때만 실행된다.
-- 코드는 해시(bcrypt)로만 저장한다. 두 표 모두 RLS 를 켜고 정책을 만들지 않아 anon 이 읽지 못한다.
-- 코드 값은 여기에 적지 않는다. 설정은 SQL Editor 에서 한 번만 (이 파일에 저장하지 말 것):
--   insert into operator_secret (id, code_hash)
--   values (1, extensions.crypt('<운영자 코드>', extensions.gen_salt('bf')))
--   on conflict (id) do update set code_hash = excluded.code_hash;
-- operator_secret 이 비어 있으면 관리자 RPC 는 전부 거부된다 (열린 채로 시작하지 않는다).
create schema if not exists extensions;
create extension if not exists pgcrypto with schema extensions;

create table if not exists operator_secret (
  id integer primary key check (id = 1),
  code_hash text not null
);

-- 코드를 틀린 시도. 최근 10분에 5번 넘게 틀리면 그 창 동안 맞는 코드도 거부한다.
create table if not exists admin_attempt (
  id bigint generated by default as identity primary key,
