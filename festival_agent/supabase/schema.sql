-- 되돌리기: 닫은 것(dismissed)이나 운영자가 지정한 것(done + decided_by='operator')을 다시 'review' 로.
create or replace function reopen_review(p_id bigint, p_code text)
returns jsonb
language plpgsql security definer set search_path = public, extensions as $$
declare
  v_err text;
  v_row classification%rowtype;
  v_raw text;
  v_was_label boolean;
begin
  v_err := admin_gate(p_code);
  if v_err is not null then
    return jsonb_build_object('ok', false, 'error', v_err);
  end if;
  select * into v_row from classification where feedback_id = p_id for update;
  if not found then
    raise exception '없는 민원입니다';
  end if;
  v_was_label := v_row.status = 'done' and v_row.decided_by = 'operator';
  if not (v_row.status = 'dismissed' or v_was_label) then
    raise exception '되돌릴 수 있는 처리가 아닙니다';
  end if;
  update classification
     set status = 'review', label = null, confidence = null,
         agent_note = '확인 필요 — 운영자가 되돌림. 모델 제안: ' || coalesce(v_row.suggested_label, '-'),
         reviewed_at = null, review_action = null, decided_by = null
   where feedback_id = p_id;
  if v_was_label then                                  -- 지정하며 넣어 둔 같은 문장 캐시는 지운다
    select raw_text into v_raw from feedback where id = p_id;
    delete from classify_cache where hash = encode(digest(v_raw, 'sha256'), 'hex');
  end if;
  return jsonb_build_object('ok', true);
end $$;

-- ── 개발자 보기 (D5-62) — 공개 읽기 전용 (운영자 코드 없음, 심사위원이 에이전트 동작을 보는 용도) ──────────
-- 공개로 나가도 안전하게: ① 읽기만 한다(쓰는 것은 호출 빈도 기록 한 줄뿐) ② 모든 문자열은 dev_redact() 로 개인정보·경로·주소·키·해시를 가린다
-- ③ 운영자 코드·operator_secret·출처 해시(admin_attempt·submit_rate 의 원본 src)·환경 키는 읽지도 않는다 ④ 한 번에 최대 200행
-- ⑤ 출처별 1분 60번 (submit_rate 에 'dev:<출처 해시>' 로 기록, 출처를 모르면 전체 공용 240번).
-- p_code 는 [화면] 호환을 위해 받기만 하고 무시한다. 관리자 동작(지우기·상태 변경 등)은 그대로 운영자 코드가 필요하다.
-- 응답: { ok, now, max_log_id, max_cls_id, logs[], classifications[], severity[], cards[], status{backend_llm, loops{}, tokens_today{}} }
-- logs: id > p_since_log 오래된 것부터 최대 200건 (p_since_log=0 이면 가장 최근 200건). 다음 호출에 max_log_id 를 그대로 넘긴다.
-- classifications: 가장 최근 40건(최신 먼저, 지운 민원 제외). p_since_cls 는 받기만 한다 (상태가 바뀌므로 매번 40건).

-- 공개 응답에 나가는 글자를 가린다. core/devfeed.ts 의 redact() 와 같은 규칙 (환경 변수 값 자체를 지우는 것은 서버 쪽만 한다).
create or replace function dev_redact(p text)
returns text
language sql immutable as $$
  select regexp_replace(regexp_replace(regexp_replace(regexp_replace(regexp_replace(regexp_replace(regexp_replace(
         regexp_replace(regexp_replace(regexp_replace(regexp_replace(regexp_replace(regexp_replace(regexp_replace(regexp_replace(
           p,
           '\$2[aby]\$[0-9]{2}\$[./A-Za-z0-9]{8,}', '[해시]', 'g'),                                          -- bcrypt (운영자 코드 해시, 잘린 앞부분 포함)
           'eyJ[A-Za-z0-9_.-]{8,}', '[키]', 'g'),                                                           -- JWT (Supabase 키, 잘린 앞부분 포함)
           '(sk|sb|pk)[-_][A-Za-z0-9_-]{8,}', '[키]', 'g'),                                                 -- API 키 모양
           'postgres(ql)?://[^[:space:]"'']+', '[DB주소]', 'g'),
           '(https?://[^[:space:]"''?]+)\?[^[:space:]"'']*', '\1?[숨김]', 'g'),                               -- 주소의 ?뒤(serviceKey 등)
           '[A-Za-z]:\\+([^"''\\]+\\+)*[^"''\\]*', '[경로]', 'g'),                                            -- Windows 경로 (공백 포함)
           '/(Users|home)/[^[:space:]"'']*', '[경로]', 'g'),
           '[0-9]{6}[[:space:]]*[-–][[:space:]]*[1-4][0-9]{6}', '[주민번호]', 'g'),
           '([0-9]{4}[-[:space:]]?){3}[0-9]{4}', '[카드번호]', 'g'),
           '01[016-9][-.[:space:]]?[0-9]{3,4}[-.[:space:]]?[0-9]{4}', '[연락처]', 'g'),
           '0[0-9]{1,2}[-.[:space:]][0-9]{3,4}[-.[:space:]][0-9]{4}', '[연락처]', 'g'),
           '[[:alnum:]_.+-]+@[[:alnum:]_-]+\.[[:alnum:]_.]+', '[이메일]', 'g'),
           '[0-9]{2,3}[가-힣][[:space:]]?[0-9]{4}', '[차량번호]', 'g'),
           '\m[0-9]{1,3}(\.[0-9]{1,3}){3}\M', '[IP]', 'g'),
           '\m[0-9a-fA-F]{12,}\M', '[해시]', 'g')
$$;

create or replace function dev_feed(p_code text default null, p_since_log bigint default 0, p_since_cls bigint default 0)
returns jsonb
language plpgsql security definer set search_path = public, extensions as $$
declare
  v_since bigint := greatest(coalesce(p_since_log, 0), 0);
  v_logs jsonb;
  v_max_log bigint;
  v_cls jsonb;
  v_sev jsonb;
  v_cards jsonb;
  v_loops jsonb;
  v_backend text;
  v_tok jsonb;
  v_today text := to_char(now() at time zone 'Asia/Seoul', 'YYYY-MM-DD');
  v_now text := to_char(now() at time zone 'Asia/Seoul', 'YYYY-MM-DD"T"HH24:MI:SS');
  v_src text := request_source();
  v_key text;
  v_limit integer;
begin
  -- 호출 빈도 제한 (submit_rate 재사용). 출처를 모르면 전체 공용 바구니.
  v_key := 'dev:' || coalesce(nullif(v_src, ''), 'all');
  v_limit := case when v_src = '' then 240 else 60 end;
  delete from submit_rate where src like 'dev:%'
     and at < to_char((now() at time zone 'Asia/Seoul') - interval '10 minutes', 'YYYY-MM-DD"T"HH24:MI:SS');
  if (select count(*) from submit_rate where src = v_key
        and at >= to_char((now() at time zone 'Asia/Seoul') - interval '60 seconds', 'YYYY-MM-DD"T"HH24:MI:SS')) >= v_limit then
    return jsonb_build_object('ok', false, 'error', '잠시 후 다시 보세요');
  end if;
  insert into submit_rate (src, at) values (v_key, v_now);

  select coalesce(jsonb_agg(to_jsonb(x) order by x.id), '[]'::jsonb), coalesce(max(x.id), v_since) into v_logs, v_max_log
    from (select y.id, y.created_at, y.agent, y.action,
                 dev_redact(y.input_summary) as input_summary, dev_redact(y.output_summary) as output_summary,
                 dev_redact(y.reasoning) as reasoning, y.latency_ms, y.tokens_in, y.tokens_out, y.tokens_cache
            from (select id, created_at, agent, action, input_summary, output_summary, reasoning, latency_ms,
                         coalesce(input_tokens, 0) as tokens_in, coalesce(output_tokens, 0) as tokens_out,
                         coalesce(cache_read_tokens, 0) as tokens_cache
                    from agent_log
                   where id > v_since
                   order by case when v_since > 0 then id end asc, id desc
                   limit 200) y) x;

  select coalesce(jsonb_agg(to_jsonb(x) order by x.feedback_id desc), '[]'::jsonb) into v_cls
    from (select c.feedback_id, dev_redact(left(f.raw_text, 120)) as raw_text, c.label, c.status, c.is_safety, c.confidence,
                 dev_redact(c.agent_note) as agent_note, c.suggested_label, c.processed_at
            from classification c join feedback f on f.id = c.feedback_id
           where f.deleted_at is null
           order by c.feedback_id desc limit 40) x;

  select coalesce(jsonb_agg(jsonb_build_object(
           'label', s.label, 'window', s."window", 'as_of', s.as_of, 'freq', s.freq, 'avg_sentiment', s.avg_sentiment,
           'base_score', s.base_score, 'safety_w', s.safety_w, 'spike_w', s.spike_w, 'pending_w', s.pending_w,
           'score', s.score, 'grade', s.grade, 'formula', s.formula, 'spike_mult', s.spike_mult, 'safety_freq', s.safety_freq)
         order by s.score desc), '[]'::jsonb) into v_sev
    from severity s where s.as_of = (select max(as_of) from severity);

  select coalesce(jsonb_agg(jsonb_build_object(
           'issue_key', i.issue_key, 'label', i.label, 'zone_name', i.zone_name, 'grade', i.grade, 'is_safety', i.is_safety,
           'card_score', i.card_score, 'formula', i.formula, 'freq', i.freq, 'type_freq', i.type_freq,
           'text_source', i.text_source, 'fail_count', i.fail_count, 'grp', i.grp, 'rank_no', i.rank_no)
         order by i.rank_no), '[]'::jsonb) into v_cards
    from issue i where i.active = 1;

  select coalesce(jsonb_object_agg(w.name, jsonb_build_object('last_at', w.last_at, 'took_ms', w.took_ms, 'ok', w.ok, 'note', dev_redact(w.note))), '{}'::jsonb)
    into v_loops from worker_status w where w.name not like '\_%';
  select note into v_backend from worker_status where name = '_backend';

  select jsonb_build_object('input', coalesce(sum(input_tokens), 0), 'output', coalesce(sum(output_tokens), 0),
                            'cache', coalesce(sum(cache_read_tokens), 0))
    into v_tok from agent_log where created_at >= v_today;

  return jsonb_build_object(
    'ok', true, 'now', v_now,
    'max_log_id', v_max_log, 'max_cls_id', (select coalesce(max(feedback_id), 0) from classification),
    'logs', v_logs, 'classifications', v_cls, 'severity', v_sev, 'cards', v_cards,
    'status', jsonb_build_object('backend_llm', v_backend, 'loops', v_loops, 'tokens_today', v_tok));
end $$;

