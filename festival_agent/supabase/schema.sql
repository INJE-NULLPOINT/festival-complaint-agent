-- 접수가 들어오면 워커를 바로 깨운다 (D5-71): feedback_inbox 에 행이 생길 때마다 pg_notify. 워커는 LISTEN 으로 받고, 놓쳐도 폴링이 예비로 받는다.
-- 수거 쿼리(feedback_id is null 인 접수 찾기)가 비어 있을 때 가볍도록 아직 안 옮긴 접수만 색인한다.
create or replace function notify_inbox()
returns trigger
language plpgsql as $$
begin
  perform pg_notify('feedback_inbox', new.id::text);
  return new;
end $$;
revoke all on function notify_inbox() from public, anon, authenticated;

