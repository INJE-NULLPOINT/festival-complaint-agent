-- ── 운영자 설정 (D5-90) — 축제 이름·지역·기간, 구역(이름 변경·숨김), 유형별 담당 부서·연락처 ───────────────
-- 쓰기는 모두 admin_gate(운영자 코드). 검증 오류는 예외(raise)로 사용자 문구를 돌려준다 (코드 검사 결과는 반환값 {ok:false,error}).
-- 구역은 지우는 RPC 가 없다 (민원이 달려 있다) — 이름 변경·숨김만. 연락처는 숫자와 하이픈만(숫자 3~20개, 하이픈은 연달아 쓰지 않음).
-- 읽기 get_settings() 는 공개(코드 없음): 설정 화면이 쓴다. departments[].is_example = 기본 예시 번호(055-000-000x)인 동안 true.
create or replace function get_settings()
returns jsonb
language sql stable security definer set search_path = public, extensions as $$
  select jsonb_build_object(
    'festival', (select to_jsonb(f) - 'id' from (select name, region, start_date, end_date from festival order by id limit 1) f),
    'zones', coalesce((select jsonb_agg(jsonb_build_object('id', z.id, 'name', z.name, 'hidden', coalesce(z.hidden, 0),
               'feedback_count', (select count(*) from feedback f where f.zone_id = z.id and f.deleted_at is null)) order by z.id) from zone z), '[]'::jsonb),
    'departments', coalesce((select jsonb_agg(jsonb_build_object('label', d.label,
               'label_ko', case d.label when 'parking' then '주차/교통' when 'restroom' then '화장실' when 'price' then '가격/바가지'
                                        when 'guide' then '안내/동선' when 'crowd' then '혼잡' when 'safety' then '안전' else d.label end,
               'department', d.department, 'contact', d.contact, 'is_example', d.contact ~ '^055-000-000[0-9]$') order by d.label) from department_map d), '[]'::jsonb));
$$;

create or replace function save_festival(p_name text, p_region text, p_start_date text, p_end_date text, p_code text)
returns jsonb
language plpgsql security definer set search_path = public, extensions as $$
declare v_err text; v_id bigint;
begin
  v_err := admin_gate(p_code);
  if v_err is not null then return jsonb_build_object('ok', false, 'error', v_err); end if;
  if btrim(coalesce(p_name, '')) = '' then raise exception '축제 이름을 입력해 주세요'; end if;
  if btrim(coalesce(p_region, '')) = '' then raise exception '지역을 입력해 주세요'; end if;
  if length(btrim(p_name)) > 40 or length(btrim(p_region)) > 40 then raise exception '이름·지역은 40자 이내로 적어 주세요'; end if;
  if p_start_date !~ '^\d{4}-\d{2}-\d{2}$' or p_end_date !~ '^\d{4}-\d{2}-\d{2}$' then raise exception '기간은 YYYY-MM-DD 형식으로 적어 주세요'; end if;
  if p_end_date < p_start_date then raise exception '끝나는 날이 시작하는 날보다 빠를 수 없습니다'; end if;
  select id into v_id from festival order by id limit 1;
  if v_id is null then
    insert into festival (name, region, start_date, end_date) values (btrim(p_name), btrim(p_region), p_start_date, p_end_date);
  else
    update festival set name = btrim(p_name), region = btrim(p_region), start_date = p_start_date, end_date = p_end_date where id = v_id;
  end if;
  return jsonb_build_object('ok', true);
end $$;

create or replace function add_zone(p_name text, p_code text)
returns jsonb
language plpgsql security definer set search_path = public, extensions as $$
declare v_err text; v_id bigint;
begin
  v_err := admin_gate(p_code);
  if v_err is not null then return jsonb_build_object('ok', false, 'error', v_err); end if;
  if btrim(coalesce(p_name, '')) = '' then raise exception '구역 이름을 입력해 주세요'; end if;
  if length(btrim(p_name)) > 30 then raise exception '구역 이름은 30자 이내로 적어 주세요'; end if;
  if exists (select 1 from zone where name = btrim(p_name)) then raise exception '같은 이름의 구역이 이미 있습니다'; end if;
  insert into zone (festival_id, name) values ((select id from festival order by id limit 1), btrim(p_name)) returning id into v_id;
  return jsonb_build_object('ok', true, 'id', v_id);
end $$;

create or replace function rename_zone(p_id bigint, p_name text, p_code text)
returns jsonb
language plpgsql security definer set search_path = public, extensions as $$
declare v_err text;
begin
  v_err := admin_gate(p_code);
  if v_err is not null then return jsonb_build_object('ok', false, 'error', v_err); end if;
  if not exists (select 1 from zone where id = p_id) then raise exception '없는 구역입니다'; end if;
  if btrim(coalesce(p_name, '')) = '' then raise exception '구역 이름을 입력해 주세요'; end if;
  if length(btrim(p_name)) > 30 then raise exception '구역 이름은 30자 이내로 적어 주세요'; end if;
  if exists (select 1 from zone where name = btrim(p_name) and id <> p_id) then raise exception '같은 이름의 구역이 이미 있습니다'; end if;
  update zone set name = btrim(p_name) where id = p_id;
  return jsonb_build_object('ok', true, 'id', p_id);
end $$;

create or replace function set_zone_hidden(p_id bigint, p_hidden boolean, p_code text)
returns jsonb
language plpgsql security definer set search_path = public, extensions as $$
declare v_err text;
begin
  v_err := admin_gate(p_code);
  if v_err is not null then return jsonb_build_object('ok', false, 'error', v_err); end if;
  if not exists (select 1 from zone where id = p_id) then raise exception '없는 구역입니다'; end if;
  update zone set hidden = case when p_hidden then 1 else 0 end where id = p_id;
  return jsonb_build_object('ok', true, 'id', p_id, 'hidden', case when p_hidden then 1 else 0 end);
end $$;

create or replace function save_department(p_label text, p_department text, p_contact text, p_code text)
returns jsonb
language plpgsql security definer set search_path = public, extensions as $$
declare v_err text;
begin
  v_err := admin_gate(p_code);
  if v_err is not null then return jsonb_build_object('ok', false, 'error', v_err); end if;
  if not exists (select 1 from department_map where label = p_label) then raise exception '부서를 정할 수 없는 유형입니다: %', p_label; end if;
  if btrim(coalesce(p_department, '')) = '' then raise exception '담당 부서를 입력해 주세요'; end if;
  if length(btrim(p_department)) > 30 then raise exception '담당 부서는 30자 이내로 적어 주세요'; end if;
  if btrim(coalesce(p_contact, '')) !~ '^[0-9](-?[0-9]){2,19}$' then raise exception '연락처는 숫자와 하이픈만 써 주세요 (예: 055-123-4567)'; end if;
  update department_map set department = btrim(p_department), contact = btrim(p_contact) where label = p_label;
  return jsonb_build_object('ok', true);
end $$;

-- 마지막 갱신 시각 (D5-86): 공개 읽기, 시각만. 화면이 '몇 초 전 갱신'과 정체 경고에 쓴다.
-- agent_at = agent_log 의 가장 최근 동작, worker_at = worker_status 루프의 가장 최근 기록 ('_'로 시작하는 줄은 제외).
create or replace function get_freshness()
returns jsonb
language sql stable security definer set search_path = public, extensions as $$
  select jsonb_build_object(
    'server_now', to_char(now() at time zone 'Asia/Seoul', 'YYYY-MM-DD"T"HH24:MI:SS'),
    'severity_at', (select max(as_of) from severity),
    'agent_at', (select max(created_at) from agent_log),
    'worker_at', (select max(last_at) from worker_status where name not like '\_%'));
$$;

