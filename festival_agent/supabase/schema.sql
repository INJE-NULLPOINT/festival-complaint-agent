-- 실시간 축제 민원 관제 AI Agent — Supabase(Postgres) 스키마
--
-- 적용: Supabase 대시보드 > SQL Editor 에 통째로 붙여 넣고 Run.
--       몇 번 실행해도 안전하다.
--
-- core/db.py 의 SQLite 스키마와 같은 구조다. 시각은 ISO 문자열(TEXT)로 둔다.
-- 에이전트 코드가 문자열 비교로 창을 자르기 때문에 두 백엔드가 같게 동작한다.
--
-- 권한 원칙
--   워커(Python)   : service 연결(SUPABASE_DB_URL) — RLS 를 거치지 않는다.
--   웹(anon 키)    : 화면에 필요한 테이블 읽기만. 쓰기는 아래 RPC 3개로만.
--                    feedback 에 직접 쓰지 못한다 → 원문은 워커가 마스킹 후 넣는다.

-- ── 테이블 ─────────────────────────────────────────────────────────

create table if not exists festival (
  id bigint generated by default as identity primary key,
  name text, region text, start_date text, end_date text
);

create table if not exists zone (
  id bigint generated by default as identity primary key,
  festival_id bigint, name text unique
);

create table if not exists feedback (
  id bigint generated by default as identity primary key,
  festival_id bigint,
  zone_id bigint,   -- NULL = 구역 미상 (외래키 없음)
  source text,            -- qr | replay | staff | cli
  raw_text text,          -- 마스킹된 본문
  posted_at text,
  ingested_at text,
  hash text unique
);

create table if not exists classification (
  feedback_id bigint primary key references feedback(id) on delete cascade,
  label text,
  sentiment double precision,
  is_safety integer,
  confidence double precision,
  status text default 'pending',   -- pending | done | review(운영자 확인, 유형 없음) | dismissed(유형 없음으로 닫음) | failed
  processed_at text,
  agent_note text
);
