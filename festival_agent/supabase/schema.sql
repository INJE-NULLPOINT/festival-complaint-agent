-- 민원 접수. 접수번호(inbox id)를 돌려준다.
create or replace function submit_feedback(p_zone_id bigint, p_text text)
returns bigint
language plpgsql security definer set search_path = public, extensions as $$
declare
  v_id bigint;
  v_src text;
  v_norm text;
  v_cut text;
  v_now timestamp := now() at time zone 'Asia/Seoul';
  -- D5-33 설계값 [확인 필요: 리허설로 조정]. 끄려면 false 로.
  v_dedup_on constant boolean := true;
  -- ②출처별 제한은 **기본 꺼짐**. x-forwarded-for 맨 오른쪽 값이 게이트웨이 주소면 모두가 한 출처로 묶여 정상 신고가 막힌다.
  -- [확인 필요] Supabase 에서 헤더가 실제 접속자 주소인지 확인한 뒤에만 true 로 켠다.
  v_limit_on constant boolean := false;
begin
  -- 한글·영문·숫자가 2개 이상이어야 한다 ('...' 'ㅋㅋ' '!!!!' 거부). core/privacy.has_content 와 같은 규칙
  if p_text is null or length(regexp_replace(p_text, '[^가-힣A-Za-z0-9]', '', 'g')) < 2 then
    raise exception '어떤 불편인지 조금 더 적어 주세요';
  end if;
  if length(p_text) > 500 then
    raise exception '500자 이내로 적어 주세요';
  end if;
  if not exists (select 1 from zone where id = p_zone_id) then
    raise exception '구역을 선택해 주세요';
  end if;
  -- ② 출처별 폭주 제한: 1분 10건 · 10분 30건. 출처를 모르면(헤더 없음) 건너뛴다. 기록은 24시간 뒤 삭제.
  v_src := request_source();
  if v_limit_on and v_src <> '' then
    delete from submit_rate where at < to_char(v_now - interval '24 hours', 'YYYY-MM-DD"T"HH24:MI:SS');
    if (select count(*) from submit_rate where src = v_src
         and at >= to_char(v_now - interval '60 seconds', 'YYYY-MM-DD"T"HH24:MI:SS')) >= 10
       or (select count(*) from submit_rate where src = v_src
            and at >= to_char(v_now - interval '600 seconds', 'YYYY-MM-DD"T"HH24:MI:SS')) >= 30 then
      raise exception '잠시 후 다시 보내 주세요';
    end if;
    insert into submit_rate (src, at) values (v_src, to_char(v_now, 'YYYY-MM-DD"T"HH24:MI:SS'));
  end if;
  -- ① 같은 글 합치기: 같은 구역 + 공백·기호를 지운 같은 본문이 2분 안에 있으면 새로 넣지 않고 같은 접수번호를 돌려준다.
  -- (워커가 옮긴 뒤에는 마스킹본과 비교하므로 개인정보가 섞인 글은 합쳐지지 않을 수 있다 — [확인 필요])
  if v_dedup_on then
    v_norm := lower(regexp_replace(p_text, '[^가-힣A-Za-z0-9]', '', 'g'));
    -- 같은 구역·같은 글이 거의 동시에 두 번 와도 한 건이 되게, 이 트랜잭션이 끝날 때까지 같은 글끼리는 줄을 세운다
    perform pg_advisory_xact_lock(hashtext(p_zone_id::text || ':' || v_norm));
    v_cut := to_char(v_now - interval '120 seconds', 'YYYY-MM-DD"T"HH24:MI:SS');
    select id into v_id from feedback_inbox
     where zone_id = p_zone_id and text is not null and created_at >= v_cut
       and lower(regexp_replace(text, '[^가-힣A-Za-z0-9]', '', 'g')) = v_norm
     order by id desc limit 1;
    if found then
      update feedback_inbox set dup_count = coalesce(dup_count, 0) + 1 where id = v_id;
      return v_id;
    end if;
    select id into v_id from feedback
     where zone_id = p_zone_id and deleted_at is null and ingested_at >= v_cut
       and lower(regexp_replace(raw_text, '[^가-힣A-Za-z0-9]', '', 'g')) = v_norm
     order by id desc limit 1;
    if found then
      update feedback set dup_count = coalesce(dup_count, 0) + 1 where id = v_id;
      return coalesce((select max(id) from feedback_inbox where feedback_id = v_id), v_id);
    end if;
  end if;
  insert into feedback_inbox (zone_id, text, created_at)
  values (p_zone_id, btrim(p_text), to_char(v_now, 'YYYY-MM-DD"T"HH24:MI:SS'))
  returning id into v_id;
  return v_id;
end $$;

